func TestW30EngineTable(t *testing.T) {
	reg := loadRealRegistry(t)

	for _, tc := range w30Table {
		sk := reg.ByName(tc.skill)
		if sk == nil {
			t.Errorf("%s not in skills.txt", tc.skill)

			continue
		}

		e := realEnv(reg, tc.skill, tc.lvl, nil)
		got := [7]int{sk.ManaCost(tc.lvl), int(sk.ElemMin(e, tc.lvl)), int(sk.ElemMax(e, tc.lvl)), sk.ElemLen(e, tc.lvl),
			int(sk.PhysMin(e, tc.lvl, 0, true)), int(sk.PhysMax(e, tc.lvl, 0, true)), e.Eval(sk.Delay)}
		want := [7]int{tc.mana, tc.emin, tc.emax, tc.elen, tc.pmin, tc.pmax, tc.delay}

		if got != want {
			t.Errorf("%s L%d: mana,emin,emax,elen,pmin,pmax,delay = %v, want %v", tc.skill, tc.lvl, got, want)
		}
	}
}
